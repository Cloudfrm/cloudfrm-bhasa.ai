    function listenChat() {
      const Rec = window.SpeechRecognition || window.webkitSpeechRecognition;
      if (!Rec) {
        speakError(t().micErr);
        track("chat_speak_used", { outcome: "unsupported" });
        return;
      }
      const rec = new Rec();
      rec.lang = replyLang === "ne" ? "ne-NP" : "en-US";
      rec.interimResults = false;
      rec.onresult = (event) => {
        const text = event.results[0][0].transcript;
        if (!text) return;
        track("chat_speak_used", { outcome: "ok" });
        paintUnicoderHint();
        logStick = true;
        sendText(text);
      };
      rec.onerror = (event) => {
        const kind = event && event.error;
        if (kind === "not-allowed" || kind === "service-not-allowed") {
          speakError(t().micBlocked);
          track("chat_speak_used", { outcome: "blocked" });
          return;
        }
        speakError(t().hearErr);
        track("chat_speak_used", { outcome: "no_speech" });
      };
      rec.start();
      mic.classList.add("hot");
      mic.setAttribute("aria-pressed", "true");
      rec.onend = () => {
        mic.classList.remove("hot");
        mic.setAttribute("aria-pressed", "false");
      };
    }

