    function humanTime(iso) {
      if (!iso) return "";
      const d = new Date(iso);
      if (isNaN(d.getTime())) return "";
      const now = new Date();
      const mins = Math.floor((now.getTime() - d.getTime()) / 60000);
      if (mins < 1) return t().timeNow;
      if (mins < 60) return t().timeMinutes.replace("{n}", replyLang === "ne" ? neNum(mins) : String(mins));
      if (d.toDateString() === now.toDateString()) return t().timeToday;
      if (d.toDateString() === new Date(now.getTime() - 86400000).toDateString()) return t().timeYesterday;
      try {
        return d.toLocaleDateString(replyLang === "ne" ? "ne-NP" : "en-GB", { day: "numeric", month: "short" });
      } catch {
        return String(iso).slice(0, 10);
      }
    }

