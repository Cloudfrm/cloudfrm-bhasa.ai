    /* A0.10 — the one adapter. Every Chat fetch goes through here, and
       this is the only place that maps transport failures onto a
       FailureCode. Server-supplied error strings are never rendered
       (they arrive in English and would break the WO10 language pass). */
    const api = {
      async request(path, options) {
        const opts = options || {};
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort("timeout"), opts.timeoutMs || SEND_TIMEOUT_MS);
        if (typeof navigator !== "undefined" && navigator.onLine === false) {
          clearTimeout(timer);
          throw { failureCode: "offline" };
        }
        try {
          const res = await fetch(path, {
            method: opts.method || "GET",
            headers: opts.headers,
            body: opts.body,
            signal: controller.signal
          });
          let data = null;
          try { data = await res.json(); } catch { data = null; }
          if (!res.ok) throw { failureCode: api.codeForStatus(res.status) };
          return data;
        } catch (err) {
          if (err && err.failureCode) throw err;
          if (err && (err.name === "AbortError" || err === "timeout")) throw { failureCode: "timeout" };
          throw { failureCode: navigator.onLine === false ? "offline" : "unknown" };
        } finally {
          clearTimeout(timer);
        }
      },
      codeForStatus(status) {
        if (status === 401 || status === 403) return "unauthorized";
        if (status === 429) return "rate_limited";
        if (status >= 500) return "server";
        return "unknown";
      },
      json(path, body, extraHeaders) {
        return api.request(path, {
          method: "POST",
          headers: Object.assign({ "Content-Type": "application/json" }, extraHeaders || {}),
          body: JSON.stringify(body)
        });
      },
      /* The backend creates the conversation implicitly on first chat,
         which is exactly the D2 default: New chat is a client-side
         draft and writes nothing until the officer sends. */
      sendMessage(payload, clientId) {
        return api.json("/v1/support/chat", payload, { "Idempotency-Key": clientId });
      },
      unicoder(text) {
        return api.request("/v1/support/unicoder", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ text }),
          timeoutMs: 6000
        });
      },
      speak(text, locale) {
        return api.json("/v1/support/speak", { text, locale });
      },
      /* Adapter shim: the store returns `preview`/`updated_at`, not
         `lastMessagePreview`/`lastMessageAt`, and has no unreadCount.
         Normalised here so no component sees the raw row. */
      async conversations(channel) {
        const rows = await api.request("/v1/support/conversations?channel=" + encodeURIComponent(channel));
        return (Array.isArray(rows) ? rows : []).map((row) => ({
          id: row.id,
          preview: row.preview || "",
          updatedAt: row.updated_at || row.created_at || null,
          messageCount: row.message_count || 0,
          isDraft: false
        }));
      },
      async messages(conversationId) {
        const data = await api.request("/v1/support/conversations/" + conversationId);
        return (data && data.messages) || [];
      },
      /* SYNTHESISED: the endpoint has no ?status=open filter and no
         `reference` field, so open tickets are filtered client-side and
         the id doubles as the reference. Real rows, not mock data. */
      async openTickets() {
        const rows = await api.request("/v1/support/tickets");
        return (Array.isArray(rows) ? rows : [])
          .filter((row) => row.status !== "resolved")
          .map((row) => ({ id: row.id, subject: row.subject || row.status, openedAt: row.created_at || null }));
      }
    };

