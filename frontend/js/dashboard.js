    async function sendText(message, options) {
      const opts = options || {};
      if (!message || sendInFlight) return;
      const clientId = opts.clientId || newClientId();
      let shown = message;
      const romanSource = opts.romanSource || (hasLatin(message) ? message : undefined);
      if (!opts.asTyped && hasLatin(message)) shown = await toUnicoder(message);

      const turn = opts.retryTurn || addTurn(log, "member", shown);
      const wrap = turn.closest(".turn");
      wrap.classList.remove("err");
      clearFailure(wrap);
      wrap.dataset.clientId = clientId;
      setBusy(true);
      showWriting();
      track("chat_message_sent", {
        lang: replyLang,
        viaChip: !!opts.viaChip,
        lengthBucket: lengthBucket(shown)
      });
      try {
        const data = await api.sendMessage(
          { message: shown, conversation_id: chatId, locale: replyLang, channel: "chat" },
          clientId
        );
        chatId = data.conversation_id;
        if (data.transliterated) turn.textContent = data.transliterated;
        clearLoading("pending");
        setConnection("online");
        addAgent(data.reply, false, data);
        loadInbox("chat");
        loadTickets();
        loadHome();
      } catch (err) {
        const code = (err && err.failureCode) || "unknown";
        clearLoading("pending");
        /* Never render a server string — map the code to our own copy,
           so Nepali mode stays Nepali when the backend fails. */
        markFailed(wrap, { clientId, body: shown, romanSource, code });
        track("chat_send_failed", { failureCode: code });
        if (code === "offline") setConnection("offline");
        else if (code === "unauthorized") setConnection("session_expired");
      } finally {
        setBusy(false);
        box.focus();
      }
    }

