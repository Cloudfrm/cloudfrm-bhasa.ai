    /* A0.11 — Bhasa answers are policy prose: they need paragraphs,
       bold and lists to be readable, not one grey slab. This renders a
       restricted subset (paragraphs, ordered and unordered lists, bold,
       links) by BUILDING NODES, never by assigning innerHTML, so server
       content cannot inject markup. No raw HTML, images or tables. */
    function safeHref(url) {
      const clean = String(url || "").trim();
      return /^https?:\/\//i.test(clean) ? clean : null;
    }

    function renderInline(target, text) {
      /* **bold** and [label](url); everything else is literal text. */
      const pattern = /\*\*([^*]+)\*\*|\[([^\]]+)\]\(([^)\s]+)\)/g;
      let cursor = 0;
      let match;
      while ((match = pattern.exec(text)) !== null) {
        if (match.index > cursor) {
          target.appendChild(document.createTextNode(text.slice(cursor, match.index)));
        }
        if (match[1] !== undefined) {
          const strong = document.createElement("strong");
          strong.textContent = match[1];
          target.appendChild(strong);
        } else {
          const href = safeHref(match[3]);
          if (href) {
            const link = document.createElement("a");
            link.href = href;
            link.target = "_blank";
            link.rel = "noopener noreferrer";
            link.textContent = match[2];
            target.appendChild(link);
          } else {
            /* An unsafe scheme degrades to plain text, never a link. */
            target.appendChild(document.createTextNode(match[0]));
          }
        }
        cursor = match.index + match[0].length;
      }
      if (cursor < text.length) {
        target.appendChild(document.createTextNode(text.slice(cursor)));
      }
    }

    /* Speech should never read "asterisk asterisk" — strip the markup
       before it reaches TTS. */
    function plainText(body) {
      return String(body == null ? "" : body)
        .replace(/\*\*([^*]+)\*\*/g, "$1")
        .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, "$1")
        .replace(/^\s*(?:[-*]|\d+[.)])\s+/gm, "");
    }

    function renderRich(target, body) {
      const blocks = String(body == null ? "" : body).split(/\n{2,}/);
      blocks.forEach((block) => {
        const lines = block.split("\n").filter((line) => line.trim() !== "");
        if (!lines.length) return;
        const bulleted = lines.every((line) => /^\s*[-*]\s+/.test(line));
        const numbered = lines.every((line) => /^\s*\d+[.)]\s+/.test(line));
        if ((bulleted || numbered) && lines.length) {
          const list = document.createElement(bulleted ? "ul" : "ol");
          lines.forEach((line) => {
            const item = document.createElement("li");
            renderInline(item, line.replace(/^\s*(?:[-*]|\d+[.)])\s+/, ""));
            list.appendChild(item);
          });
          target.appendChild(list);
          return;
        }
        const para = document.createElement("p");
        /* Single newlines inside a block stay as line breaks. */
        lines.forEach((line, index) => {
          if (index) para.appendChild(document.createElement("br"));
          renderInline(para, line);
        });
        target.appendChild(para);
      });
      if (!target.childNodes.length) target.textContent = body || "";
    }

