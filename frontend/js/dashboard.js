    function listenCall() {
      if (!callLive || callBusy) return;
      const Rec = window.SpeechRecognition || window.webkitSpeechRecognition;
      if (!Rec) { addTurn(callLog, "agent", t().micErr, true); return; }
      const rec = new Rec();
      callRec = rec;
      rec.lang = replyLang === "ne" ? "ne-NP" : "en-US";
      rec.interimResults = false;
      rec.onresult = async (event) => {
        const text = event.results[0][0].transcript;
        if (!text || !callLive) return;
        callBusy = true;
        try { rec.stop(); } catch {}
        await sendCallTurn(text);
        callBusy = false;
        if (callLive) listenCall();
      };
      rec.onerror = () => {
        if (callLive && !callBusy) addTurn(callLog, "agent", t().hearErr, true);
      };
      rec.onend = () => {
        callRec = null;
        if (callLive && !callBusy) setTimeout(() => { if (callLive && !callBusy) listenCall(); }, 500);
      };
      try { rec.start(); } catch {}
    }

