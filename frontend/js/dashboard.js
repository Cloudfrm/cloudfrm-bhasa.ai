    async function speakReply(text, wait) {
      if (!text) return;
      if (!wait && !speakOn) return;
      try {
        const res = await fetch("/v1/support/speak", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ text, locale: replyLang })
        });
        const data = await res.json();
        if (res.ok && data.audio_base64) {
          if (lastAudio) lastAudio.pause();
          lastAudio = new Audio("data:" + (data.mime || "audio/mpeg") + ";base64," + data.audio_base64);
          const done = lastAudio.play().catch(() => {});
          if (wait) await new Promise((resolve) => { lastAudio.onended = resolve; lastAudio.onerror = resolve; });
          await done;
        }
      } catch {}
    }

